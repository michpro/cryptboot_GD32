constexpr uint32_t                  APP_STORE_BASE_ADDRESS      {FIRMWARE_STORE_BASE_ADDRESS + sizeof(firmwareCfg_t)};
constexpr uint32_t                  APP_MAX_SIZE                {APP_STORE_OFFSET - APP_OFFSET - sizeof(firmwareCfg_t)};

// --- Internal State Buffers ---
static firmwareCfg_t                firmwareConfig;
static bootCfg_t                    bootConfig;
static uint8_t                      buffer[PAGE_SIZE_BYTE];         ///< Shared buffer for flash operations

// --- Algorithm Identifiers (Mode Bitfield) ---
const uint8_t                       SIG_ECDSA_P256              {0x00};
const uint8_t                       HASH_SHA256                 {0x00};
const uint8_t                       NEW_KEY_NONE                {0x00};
const uint8_t                       NEW_KEY_AES256              {0x04};
const uint8_t                       FIRMWARE_CIPHER_NONE        {0x00};
const uint8_t                       FIRMWARE_CIPHER_AES256      {0x01};

// --- Crypto Mode Helper Macros ---
#define GET_MODE_SIG_TYPE()         ((uint8_t)(firmwareConfig.mode & 0xC0))
#define GET_MODE_HASH_TYPE()        ((uint8_t)(firmwareConfig.mode & 0x30))
#define GET_MODE_NEW_KEY_CIPHER()   ((uint8_t)(firmwareConfig.mode & 0x0C))
#define GET_MODE_FIRMWARE_CIPHER()  ((uint8_t)(firmwareConfig.mode & 0x03))

#define MODE_SIG_PARAMS_OK()        ((SIG_ECDSA_P256 == GET_MODE_SIG_TYPE()) && (HASH_SHA256  == GET_MODE_HASH_TYPE()))
#define MODE_NEW_KEY_CIPHER_OK()    ((NEW_KEY_NONE == GET_MODE_NEW_KEY_CIPHER()) || (NEW_KEY_AES256 == GET_MODE_NEW_KEY_CIPHER()))
#define MODE_FIRMWARE_CIPHER_OK()   ((FIRMWARE_CIPHER_NONE == GET_MODE_FIRMWARE_CIPHER()) || (FIRMWARE_CIPHER_AES256 == GET_MODE_FIRMWARE_CIPHER()))

// firmwareCfg_t
// version
//   0x11 => 1.1
//
// mode
//   ---------------------------------------------------------
//   Bit Number   Contents
//   ----------   --------------------------------------------
//   7 ... 6      signature type
//                    00 - ECDSA P-256
//                    01 - RFU (Reserved for Future Use)
//                    10 - RFU
//                    11 - RFU
//   5 ... 4      hash type
//                    00 - SHA256
//                    01 - RFU
//                    10 - RFU
//                    11 - RFU
//   3 ... 2      new key cipher type
//                    00 - no new key
//                    01 - AES256
//                    10 - RFU
//                    11 - RFU
//   1 ... 0      firmware cipher type
//                    00 - none
//                    01 - AES256
//                    10 - RFU
//                    11 - RFU
//   ---------------------------------------------------------
//
// timeStamp
//   ---------------------------------------------------------
//   Bit Number   Contents
//   ----------  --------------------------------------------
//   31 ... 20    YYYY
//   19 ... 16    MM (month)
//   15 ... 11    DD
//   10 ... 06    HH
