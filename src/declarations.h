/**
 * @union u32_u16_union_t
 * @brief Utility union for reset reason handling.
 * Maps the 32-bit Reset Status register to two 16-bit backup registers.
 */
typedef union u32_u16_union
{
    uint32_t                        u32;
    uint16_t                        u16[sizeof(uint32_t) / sizeof(uint16_t)];
} u32_u16_union_t;

/**
 * @struct bootCfg_t
 * @brief Current system state stored in NVStorage.
 * Tracks the metadata of the successfully installed and active application.
 */
typedef struct __attribute__((packed, aligned(sizeof(uint32_t))))
{
    uint8_t                         key[AES256::KEY_SIZE];          ///< Active AES-256 decryption key
    uint32_t                        timeStamp;                      ///< Last verified firmware timestamp
    uint32_t                        firmwareSize;                   ///< App binary size in bytes
    uint32_t                        firmwareCrc32;                  ///< Expected CRC32 for the application
} bootCfg_t;

/**
 * @struct firmwareCfg_t
 * @brief 128-byte secure header for firmware update images.
 * @details This header is used by the 'firmware_image_builder.py' to wrap binary data.
 * * Timestamp bit mapping:
 * - 31-20: Year (YYYY)
 * - 19-16: Month (MM)
 * - 15-11: Day (DD)
 * - 10-06: Hour (HH)
 * - 05-00: Minute (MM)
 */
typedef struct __attribute__((packed, aligned(sizeof(uint32_t))))
{
    uint8_t                         version;                            ///< Header protocol version (0x11)
    uint8_t                         mode;                               ///< Bitfield for crypto algorithm selection
    uint8_t                         rfuA[2];                            ///< Reserved for alignment/future use
    uint32_t                        timeStamp;                          ///< Packed release date/time
    uint32_t                        firmwareSize;                       ///< Encrypted payload size
    uint32_t                        firmwareCrc32;                      ///< Integrity check of the decrypted image
    uint8_t                         signature[P256::LENGTH_SIGNATURE];  ///< ECDSA P-256 Auth tag
    uint8_t                         cipherIv[AES256::IV_SIZE];          ///< AES-256-CFB Initialization Vector
    uint8_t                         newKey[AES256::KEY_SIZE];           ///< Optional encrypted new key update
} firmwareCfg_t;                                                        //  128 bytes length

// --- Address Map ---
constexpr uint32_t                  FIRMWARE_STORE_BASE_ADDRESS {FLASH_BASE + APP_STORE_OFFSET};
constexpr uint32_t                  APP_START_ADDRESS           {FLASH_BASE + APP_OFFSET};
